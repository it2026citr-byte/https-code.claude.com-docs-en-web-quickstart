/**
 * Отбор сигналов после стратегий.
 *
 * Стратегия отвечает на вопрос «есть ли вход». Здесь отвечаем на другой:
 * «стоит ли его показывать». Разделение не косметическое — условия ниже
 * общие для всех стратегий и меряются на всём потоке сигналов сразу,
 * а не внутри каждой.
 *
 * ── Откуда взялись условия ──
 *
 * Замер: 3355 сигналов, 41 пара, 46 недель (октябрь 2025 — август 2026),
 * ведение сделки как в боте — по пятой части на каждой из пяти целей,
 * стоп в безубыток после первой. Проверялись девять признаков; отобраны
 * три, которые дали прибавку во ВСЕХ пяти срезах: обе половины монет и
 * все три трети периода. Шесть остальных отсеялись — среди них те, что
 * на всей выборке выглядели убедительно (объём, волатильность монеты,
 * место входа в диапазоне), но в отдельных срезах меняли знак.
 *
 *   согласие с биткоином   отсекает 990 сигналов из 3355, средний R
 *                          оставшихся +0.109 против +0.076
 *   согласие стратегий     отсекает 1202, оставшиеся +0.100
 *   старший тренд          отсекает 281, оставшиеся +0.086
 *
 * Вместе: 1536 сигналов вместо 3355, средний R +0.144 против +0.076.
 *
 * ── Почему это не подгонка ──
 *
 * Контроль случайным входом: та же монета, та же сторона, та же
 * геометрия, но вход на случайном баре в пределах 40 часов ПОСЛЕ
 * сигнала (только вперёд — назад бот заглядывать не может).
 *
 *   без отбора   сигнал +0.076 против случайного +0.041 → превосходство +0.035
 *   с отбором    сигнал +0.144 против случайного +0.031 → превосходство +0.112
 *
 * Отбор не добавляет сделок и не меняет геометрию — он только убирает
 * те входы, где превосходство над случайным близко к нулю.
 *
 * ── Чего отбор НЕ делает ──
 *
 * Доля тяжёлых стопов почти не меняется: 30% до отбора, 29% после.
 * Отбор поднимает средний результат сделки, но не спасает от стопа —
 * за это отвечает порог безубытка в /settings, а не эти условия.
 */

/** Ход биткоина за сутки на момент такта. Общая погода для всего рынка. */
let btc = { at: 0, chg: null };

export async function refreshMarket() {
  if (Date.now() - btc.at < 10 * 60_000) return btc.chg;
  try {
    const c = await candles("BTCUSDT", "1h", 30);
    if (c.length >= 25) {
      const i = c.length - 2;                       // последний закрытый бар
      btc = { at: Date.now(), chg: (c[i].c / c[i - 24].c - 1) * 100 };
    }
  } catch (e) {
    log("погоду по биткоину не взял:", e.message);  // тогда условие не применяется
  }
  return btc.chg;
}

export const btcChange = () => btc.chg;

/**
 * Сколько стратегий сейчас в работе. Нужно условию «согласие»: если
 * стратегия осталась одна, согласиться не с кем, и условие отсекло бы
 * ВСЁ — бот молчал бы намертво, а причина выглядела бы как поломка.
 */
let loaded = 0;
export const setStrategyCount = (n) => { loaded = n; };

/**
 * Причина отказа или null, если сигнал стоит показать.
 *
 * @param f     собранный сигнал: side, parts (какие стратегии сошлись)
 * @param cndl  свечи той же пары и того же таймфрейма, что видела стратегия
 * @param i     индекс последнего закрытого бара
 */
export function rejectSignal(f, cndl, i) {
  // Против суточного хода биткоина. Самое сильное из трёх условий:
  // +0.067R в первой трети периода, +0.006 во второй, +0.025 в третьей.
  if (num("f_btc") === 1 && btc.chg != null) {
    const withBtc = f.side === "long" ? btc.chg > 0 : btc.chg < 0;
    if (!withBtc)
      return `биткоин идёт ${btc.chg > 0 ? "вверх" : "вниз"} (${btc.chg.toFixed(1)}% за сутки), ` +
             `а сигнал в другую сторону`;
  }

  // Ни одна другая стратегия не согласна. Отсекает больше трети потока,
  // и это самый крупный отсев — но и самый ровный по срезам.
  //
  // При одной стратегии условие не применяется: согласиться не с кем,
  // и оно отсекло бы весь поток. Молчащий бот и бот без сигналов
  // выглядят одинаково, поэтому проверка здесь, а не в настройках.
  if (num("f_agree") === 1 && loaded >= 2 && (f.parts?.length ?? 1) < 2)
    return "сигнал одиночный, другие стратегии входа здесь не видят";

  // Фигура графика. Требуем не наличия любой фигуры, а фигуры В СТОРОНУ
  // входа: «фигура за» даёт +0.107R против +0.021R у сигналов без фигур
  // и −0.046R при фигуре против. Поверх остальных трёх условий прибавка
  // сохраняется во всех пяти срезах: +0.144 → +0.181.
  //
  // Сигнал без разбора фигур (свечей не хватило) не отсекается: молчание
  // детектора — не то же самое, что «фигуры нет».
  if (num("f_figure") === 1 && Array.isArray(f.figures)) {
    const want = f.side === "long" ? 1 : -1;
    if (!f.figures.some(x => x.dir === want))
      return f.figures.some(x => x.dir === -want)
        ? "фигура графика смотрит против входа"
        : "на графике нет фигуры в сторону входа";
  }

  // Снайперские сигналы. В положении «только они» (2) без сильной
  // фигуры сигнал не проходит; в положении «вместе» (1) проходит всё,
  // а сильная фигура лишь помечает карточку — пометку ставит движок.
  // Долю минусов режим не снижает (она упирается в геометрию), но
  // средний R снайперского сигнала в полтора раза выше: СТРАТЕГИИ.md, 5д.
  if (num("f_sniper") === 2 && Array.isArray(f.figures) &&
      !strongFor(f.figures, f.side))
    return "снайперский отбор: нет сильной фигуры (★) в сторону входа";

  // Против старшего тренда. Отсекает мало (8%), но убранные дают −0.029R,
  // то есть в среднем убыточны сами по себе.
  if (num("f_trend") === 1 && cndl && cndl.length > 210) {
    const e = ema(cndl.map(b => b.c), 200)[i];
    if (e != null) {
      const withTrend = f.side === "long" ? cndl[i].c > e : cndl[i].c < e;
      if (!withTrend)
        return `цена ${f.side === "long" ? "ниже" : "выше"} средней за 200 часов — ` +
               `вход против старшего тренда`;
    }
  }

  return null;
}

log("отбор сигналов подключён");
